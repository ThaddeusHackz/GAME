static Texture *s_atlas = NULL;
static int s_tex = -1;

void font_init(void) {
    if (s_atlas) return;
    s_atlas = tex_new(ATLAS_W, ATLAS_H, "font_atlas");
    if (!s_atlas) { DH_ERROR("font", "atlas alloc failed"); return; }
    for (int y = 0; y < ATLAS_H; y++)
        for (int x = 0; x < ATLAS_W; x++)
            tex_set_pixel(s_atlas, x, y, 0x00FFFFFFu);   /* white, alpha 0 */

    for (int g = 0; g <= FONT_LAST - FONT_FIRST; g++) {
        int gx = (g % ATLAS_COLS) * FONT_CELL_W;
        int gy = (g / ATLAS_COLS) * FONT_CELL_H;
        for (int row = 0; row < FONT_CELL_H; row++) {
            unsigned char bits = GLYPHS[g][row];
            for (int col = 0; col < FONT_GLYPH_W; col++) {
                if (bits & (0x80u >> col))
                    tex_set_pixel(s_atlas, gx + col, gy + row, 0xFFFFFFFFu);
            }
        }
    }
    tex_build_mips(s_atlas);
    s_tex = tex_register(s_atlas);
    DH_INFO("font", "atlas %dx%d, %d glyphs, tex id %d",
            ATLAS_W, ATLAS_H, FONT_LAST - FONT_FIRST + 1, s_tex);
}

void font_shutdown(void) {
    /* texture is owned by the registry (tex_release_all) — drop our handle */
    s_atlas = NULL; s_tex = -1;
}

int font_tex(void)   { return s_tex; }
int font_ready(void) { return s_tex >= 0; }

float font_height(float scale) { return (float)FONT_CELL_H * scale; }

float font_width(const char *s, float scale) {
    if (!s) return 0.0f;
    int n = 0;
    for (const char *c = s; *c; c++) n++;
    if (n == 0) return 0.0f;
    return (float)((n - 1) * FONT_ADVANCE + FONT_GLYPH_W) * scale;
}

void font_text(float x, float y, float scale, const char *s, uint32_t color) {
    if (!s || s_tex < 0 || scale <= 0.0f) return;
    const Texture *t = tex_get(s_tex);
    if (!t) return;
    float invw = 1.0f / (float)(t->w - 1);
    float invh = 1.0f / (float)(t->h - 1);
    float pen = x;
    for (const char *c = s; *c; c++) {
        unsigned char ch = (unsigned char)*c;
        if (ch == '\n') { y += (float)FONT_CELL_H * scale + scale; pen = x; continue; }
        if (ch < FONT_FIRST || ch > FONT_LAST) ch = '?';
        int g = ch - FONT_FIRST;
        float gx = (float)((g % ATLAS_COLS) * FONT_CELL_W);
        float gy = (float)((g / ATLAS_COLS) * FONT_CELL_H);
        /* half-texel inset so scale 1 is pixel-exact under bilinear CLAMP */
        float u0 = (gx - 0.5f) * invw;
        float u1 = (gx - 0.5f + (float)FONT_GLYPH_W) * invw;
        float v0 = (gy - 0.5f) * invh;
        float v1 = (gy - 0.5f + (float)FONT_CELL_H) * invh;
        rend_quad2d(pen, y, (float)FONT_GLYPH_W * scale, (float)FONT_CELL_H * scale,
                    s_tex, u0, v0, u1, v1, color);
        pen += (float)FONT_ADVANCE * scale;
    }
}

void font_text_shadow(float x, float y, float scale, const char *s, uint32_t color) {
    uint32_t sh = (uint32_t)((color & 0x00FFFFFFu) | (0x90u << 24));
    font_text(x + scale, y + scale, scale, s, sh);
    font_text(x, y, scale, s, color);
}

void font_text_right(float right_x, float y, float scale, const char *s, uint32_t color) {
    font_text(right_x - font_width(s, scale), y, scale, s, color);
}

void font_text_center(float cx, float y, float scale, const char *s, uint32_t color) {
    font_text(cx - font_width(s, scale) * 0.5f, y, scale, s, color);
}

void font_text_fmt(float x, float y, float scale, uint32_t color, const char *fmt, ...) {
    char buf[512];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    font_text(x, y, scale, buf, color);
}
